"""Section 4 figure: time after one switch on Qwen3-32B, relative to keeping the full context (L); no model calls.

Run from the repository root:
  python3 results/paper-mlsys2027-draft/figures/selfhosted-timeline/build_figure.py [--paste]
Input: the public scalar tables of the Qwen3-32B supplement (one Vig64 point):
  qwen3-mlsys-n3/QWEN3_MLSYS_TIMELINE.csv  wall clock with the original tool gaps, three runs per policy; L is the
                                      matched run without a summary; panel (a) draws the mean of the per-run differences
  qwen3-validation-n2/QWEN3_VALIDATION_CUMULATIVE.csv  engine time without tool gaps, two runs per policy in separate
                                      sessions, measured, and reconstructed beforehand from the frozen fixed-length
                                      calibration (the same reconstruction for both runs)
The two use different clocks and are drawn in separate panels. --paste replaces the generated block in main.tex.
"""
import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parents[1]
ROOT = HERE.parents[3]
TABLES = ROOT / "results/colab-mechanism-20261005/tables/qwen3-mlsys-n3"
VALIDATION = ROOT / "results/colab-mechanism-20261005/tables/qwen3-validation-n2"
BEGIN, END = "% BEGIN generated self-hosted timeline figure", "% END generated self-hosted timeline figure"
YMIN, YMAX = -150, 100


def fmt(points):
    return " ".join(f"({x},{y:.4g})" for x, y in points)


def rows(name, folder=TABLES):
    return list(csv.DictReader(open(folder / name)))


def first_below(diff):
    return next((j for j, d in diff if d < 0), None)


def collect():
    wall = defaultdict(dict)
    for r in rows("QWEN3_MLSYS_TIMELINE.csv"):
        wall[(r["repetition"], r["condition"])][int(r["j"])] = float(r["cumulative_wall_s"])
    reps = sorted({rep for rep, _ in wall})
    engine = defaultdict(dict)
    for r in rows("QWEN3_VALIDATION_CUMULATIVE.csv", VALIDATION):
        engine[(r["repetition"], r["condition"])][int(r["j"])] = (float(r["actual_engine_cumulative_s"]),
                                                                  float(r["frozen_reconstructed_engine_cumulative_s"]))
    eruns = sorted({rep for rep, _ in engine})
    steps = range(1, 21)
    data = dict(schema="selfhosted-timeline/v3", point="Vig64 (glm-b001-interleaved-vigenere-64k)", model="Qwen/Qwen3-32B",
                wall_runs_per_policy=len(reps), engine_runs_per_policy=len(eruns), wall={}, engine={})
    for c in ("S", "A"):
        # paired difference from the L run of the same repetition, then the mean over repetitions
        per_run = {rep: [(j, wall[(rep, c)][j] - wall[(rep, "L")][j]) for j in steps] for rep in reps}
        diff = [(j, sum(dict(per_run[rep])[j] for rep in reps) / len(reps)) for j in steps]
        spread = max(max(dict(per_run[rep])[j] for rep in reps) - min(dict(per_run[rep])[j] for rep in reps) for j in steps)
        data["wall"][c] = dict(diff_s=diff, per_run_diff_s=per_run, max_spread_s=spread, first_below_l=first_below(diff),
                               first_below_l_per_run=[first_below(per_run[rep]) for rep in reps],
                               total_s=sum(wall[(rep, c)][20] for rep in reps) / len(reps),
                               l_total_s=sum(wall[(rep, "L")][20] for rep in reps) / len(reps))
    for c in ("S", "K"):
        # each run against the L run of the same session; the frozen reconstruction is the same for both runs
        meas = {rep: [(j, engine[(rep, c)][j][0] - engine[(rep, "L")][j][0]) for j in steps] for rep in eruns}
        recon = [(j, engine[(eruns[0], c)][j][1] - engine[(eruns[0], "L")][j][1]) for j in steps]
        spread = max(max(dict(meas[rep])[j] for rep in eruns) - min(dict(meas[rep])[j] for rep in eruns) for j in steps)
        data["engine"][c] = dict(measured_diff_s=meas, reconstructed_diff_s=recon, max_spread_s=spread,
                                 first_below_l=[first_below(meas[rep]) for rep in eruns],
                                 reconstructed_first_below_l=first_below(recon),
                                 margin_at_first_below_s=[dict(meas[rep])[first_below(meas[rep])] for rep in eruns])
    data["engine"]["L_total_s"] = [engine[(rep, "L")][20][0] for rep in eruns]
    return data


def write_tex(data):
    spread = max(data["wall"][c]["max_spread_s"] for c in ("S", "A"))
    L = [BEGIN, "% Generated by figures/selfhosted-timeline/build_figure.py; data in the same directory.",
         r"\begin{figure}[t]", r"\centering", r"\begin{tikzpicture}",
         r"\begin{groupplot}[group style={group size=2 by 1,horizontal sep=0.3cm,y descriptions at=edge left},",
         r"scale only axis,width=0.37\columnwidth,height=2.3cm,xmin=0.5,xmax=20.5,ymin=" + str(YMIN) + ",ymax=" + str(YMAX) + ",",
         r"xtick={1,5,10,15,20},ytick={-150,-100,-50,0,50,100},xlabel={Step after the switch},ylabel={Time minus L's (s)},",
         r"tick label style={font=\scriptsize},label style={font=\small},title style={font=\small},",
         r"axis line style={black!45},tick style={black!45},grid=major,grid style={black!8},clip=false]",
         r"\nextgroupplot[title={(a) Wall clock}]",
         r"\addplot[black!60,line width=0.5pt,forget plot] coordinates {(0.5,0)(20.5,0)};"]
    for c, mark in (("S", "*"), ("A", "square*")):
        w = data["wall"][c]
        L.append(r"\addplot[pol" + c + r",line width=0.8pt,no marks,forget plot] coordinates {" + fmt(w["diff_s"]) + "};")
        j = w["first_below_l"]
        L.append(r"\addplot[pol" + c + r",only marks,mark=" + mark + r",mark size=1.5pt,forget plot] coordinates {" +
                 fmt([(j, dict(w["diff_s"])[j])]) + "};")
        x, y = w["diff_s"][-1]
        L.append(r"\node[font=\scriptsize,anchor=west,text=pol" + c + r"] at (axis cs:" + f"{x},{y:.4g}" + r") {" + c + "};")
    L += [r"\nextgroupplot[title={(b) Engine, no tool gaps}]",
          r"\addplot[black!60,line width=0.5pt,forget plot] coordinates {(0.5,0)(20.5,0)};"]
    for c, mark, anchor in (("S", "*", "north west"), ("K", "triangle*", "south west")):
        e = data["engine"][c]
        runs = list(e["measured_diff_s"].values())
        for diff in runs:
            L.append(r"\addplot[pol" + c + r",line width=0.8pt,no marks,forget plot] coordinates {" + fmt(diff) + "};")
        L.append(r"\addplot[pol" + c + r",dashed,line width=0.5pt,no marks,forget plot] coordinates {" + fmt(e["reconstructed_diff_s"]) + "};")
        L.append(r"\addplot[pol" + c + r",only marks,mark=" + mark + r",mark size=1.5pt,forget plot] coordinates {" +
                 fmt([(j, dict(diff)[j]) for diff, j in zip(runs, e["first_below_l"])]) + "};")
        x, y = runs[0][-1]
        L.append(r"\node[font=\scriptsize,anchor=" + anchor + r",inner sep=1pt,text=pol" + c + r"] at (axis cs:" + f"{x},{y:.4g}" + r") {" + c + "};")
    espread = max(data["engine"][c]["max_spread_s"] for c in ("S", "K"))
    L += [r"\end{groupplot}", r"\end{tikzpicture}",
          r"\caption{Time after one switch at Vig64 on Qwen3-32B relative to keeping the full context (L). (a)~Wall",
          r"clock with the original tool gaps, mean time differences from matched L across three runs per policy;",
          r"these differences varied by under " + f"{math.ceil(10 * spread) / 10:.1f}" + r"\,s at every step. L is a matched run without a summary.",
          r"S used its summary from step 1, after waiting for it, and A from step 2. (b)~Engine time without tool gaps,",
          r"two runs per policy in separate sessions; time differences from matched L varied by under " + f"{math.ceil(10 * espread) / 10:.1f}" + r"\,s",
          r"at every step. Measured (solid) and reconstructed before the runs (dashed).",
          r"Filled marks: first step below L in each run.}",
          r"\label{fig:selfhosted}", r"\end{figure}", END]
    tex = "\n".join(L) + "\n"
    (HERE / "selfhosted-timeline-pgfplots.tex").write_text(tex)
    return tex


def paste(tex):
    main = PAPER / "main.tex"
    s = main.read_text()
    if BEGIN not in s or END not in s:
        raise SystemExit("markers not found in main.tex")
    a, b = s.index(BEGIN), s.index(END) + len(END) + 1
    main.write_text(s[:a] + tex + s[b:])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--paste", action="store_true")
    args = parser.parse_args()
    data = collect()
    (HERE / "selfhosted-timeline-data.json").write_text(json.dumps(data, indent=1) + "\n")
    tex = write_tex(data)
    if args.paste:
        paste(tex)
    for c in ("S", "A"):
        w = data["wall"][c]
        print(f"wall {c}: first below L at step {w['first_below_l']} (per run {w['first_below_l_per_run']}), mean total "
              f"{w['total_s']:.1f} s vs L {w['l_total_s']:.1f} s ({100 * (w['total_s'] - w['l_total_s']) / w['l_total_s']:+.1f}%), "
              f"time differences from matched L vary by at most {w['max_spread_s']:.3f} s")
    for c in ("S", "K"):
        e = data["engine"][c]
        print(f"engine {c}: measured first below L at steps {e['first_below_l']} per run (margins "
              f"{', '.join(f'{m:.3f}' for m in e['margin_at_first_below_s'])} s), reconstructed {e['reconstructed_first_below_l']}, "
              f"time differences from matched L vary by at most {e['max_spread_s']:.3f} s")


if __name__ == "__main__":
    main()
