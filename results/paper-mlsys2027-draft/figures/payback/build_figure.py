"""Section 5 figure: decoding time against context, and the steps a summary needs to repay its cost against the
steps it was used; no provider or model calls.

Run from the repository root:
  python3 results/harness-diagnosis-20260927/compaction-payback-20261004/analyze.py
  python3 results/paper-mlsys2027-draft/figures/payback/build_figure.py [--paste]
Input: compaction-payback-20261004/payback.json (completed API S runs and the Colab
replays). --paste replaces the generated block in main.tex so the manuscript stays self-contained.
"""
import argparse
import json
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parents[1]
ROOT = HERE.parents[3]
DATA = ROOT / "results/harness-diagnosis-20260927/compaction-payback-20261004/payback.json"
BEGIN, END = "% BEGIN generated payback figure", "% END generated payback figure"
XMIN, XMAX, YMIN, YMAX = 0.8, 300, 1, 30000
MODEL = dict(qwen38="Qwen3.8-27B", qwen3="Qwen3-32B")


def fmt(points):
    return " ".join(f"({x:.4g},{y:.4g})" for x, y in points)


def jitter(i):
    # deterministic spread of +-0.06 decades, so that summaries used for the same number of steps stay visible
    return 10 ** (0.06 * (2 * ((i * 0.6180339887) % 1.0) - 1))


def collect():
    d = json.loads(DATA.read_text())
    api = [a for a in d["api"] if "repay_steps" in a and not a["cut_by_run_end"]]
    replay = [p for p in d["replay"] if p["condition"] == "S" and p["repay_steps"] is not None and not p["cut_by_run_end"]]
    panels = []
    for key, title in (("glm", "GLM"), ("deepseek", "DeepSeek")):
        mine = [a for a in api if a["model"] == key]
        runs = {}
        for a in mine:
            runs.setdefault((a["task"], a["thr"], a["rep"]), []).append(a)
        medians = [(st.median(a["steps_used"] for a in v), st.median(a["repay_steps"] for a in v)) for v in runs.values()]
        panels.append(dict(key=key, title=title, points=[(a["steps_used"], a["repay_steps"]) for a in mine], run_medians=medians,
                           runs_mostly_repaid=sum(sum(a["repay_steps"] < a["steps_used"] for a in v) > len(v) / 2 for v in runs.values()),
                           runs=len(runs)))
    for key in ("qwen38", "qwen3"):
        mine = [p for p in replay if p["deployment"] == key]
        crossed = lambda p: any(c.isdigit() for c in p["crossing_within_20"])
        panels.append(dict(key=key, title=MODEL[key],
                           points=[(p["steps_used"], p["repay_steps"]) for p in mine if not crossed(p)],
                           crossed=[(p["steps_used"], p["repay_steps"]) for p in mine if crossed(p)],
                           repaid=sum(p["repay_steps"] < p["steps_used"] for p in mine), n=len(mine)))
    return dict(schema="payback-figure/v3", panels=panels, decode=d["decode"], prices=d["notes"]["pricing"],
                notes=dict(api="S runs; summaries cut short by the run end are left out; run medians over each run's summaries",
                           replay="S replays; vertical position is the linear projection beyond the 20 replayed steps; "
                                  "crossed = the reconstructed 20-step time fell below L's within the replay; steps used "
                                  "from the GLM source run"))


def write_tex(data):
    for panel in data["panels"]:
        points = ([(x * jitter(i), y) for i, (x, y) in enumerate(panel["points"])] + panel["run_medians"]
                  if "run_medians" in panel else panel["points"] + panel["crossed"])
        if any(not (XMIN <= x <= XMAX and YMIN <= y <= YMAX) for x, y in points):
            raise ValueError("Payback bounds would truncate a plotted point")
    dec = data["decode"]
    L = [BEGIN, "% Generated by figures/payback/build_figure.py; data in the same directory.",
         r"\begin{figure*}[t]", r"\centering",
         r"\begin{tikzpicture}[baseline]",
         r"\begin{axis}[scale only axis,width=0.17\textwidth,height=2.9cm,xmin=0,xmax=210,ymin=35,ymax=64,",
         r"xtick={0,50,100,150,200},ytick={40,50,60},xlabel={Context (K tokens)},ylabel={Decoding (ms/token)},",
         r"tick label style={font=\scriptsize},label style={font=\small},title style={font=\small},title={(a) Decoding time},",
         r"axis line style={black!45},tick style={black!45},grid=major,grid style={black!8},clip=false]"]
    for key, style, anchor in (("qwen38", "solid", "south east"), ("qwen3", "dashed", "north west")):
        d = dec[key]
        pts = [(x / 1000, y) for x, y in zip(d["context_tokens"], d["ms_per_output_token"])]
        L.append(r"\addplot[black," + style + r",line width=0.7pt,mark=*,mark size=1pt,mark options={solid}] coordinates {" + fmt(pts) + "};")
        later = [(x / 1000, y) for x, y in zip(d["context_tokens"], d["ms_per_output_token"]) if x in d.get("later_session_context_tokens", [])]
        if later:
            # measured in a later session of the same deployment; drawn open
            L.append(r"\addplot[black,only marks,mark=*,mark size=1.6pt,mark options={solid,fill=white},forget plot] coordinates {" + fmt(later) + "};")
        x, y = pts[-1]
        dy = 0.6 if anchor == "south east" else 0.0
        L.append(r"\node[font=\scriptsize,anchor=" + anchor + r",inner sep=2pt] at (axis cs:" + f"{x:.4g},{y + dy:.4g}" + r") {" + MODEL[key] + "};")
    L += [r"\end{axis}", r"\end{tikzpicture}\hspace{0.45cm}%", r"\begin{tikzpicture}[baseline]",
          r"\begin{groupplot}[group style={group size=4 by 1,horizontal sep=0.22cm,y descriptions at=edge left},",
          r"scale only axis,width=0.135\textwidth,height=2.9cm,xmode=log,ymode=log,xmin=" + str(XMIN) + ",xmax=" + str(XMAX) +
          ",ymin=" + str(YMIN) + ",ymax=" + str(YMAX) + ",",
          r"xtick={1,10,100},xticklabels={1,10,100},ytick={1,10,100,1000,10000},yticklabels={1,10,100,1K,10K},",
          r"xlabel={Steps used},ylabel={Steps to repay},tick label style={font=\scriptsize},label style={font=\small},",
          r"title style={font=\small},axis line style={black!45},tick style={black!45},clip=true]"]
    for i, p in enumerate(data["panels"]):
        api = p["key"] in ("glm", "deepseek")
        L.append(r"\nextgroupplot[title={(" + "bcde"[i] + ") " + p["title"] + "}]")
        L.append(r"\addplot[fill=black!5,draw=none,forget plot] coordinates {" + fmt([(1, 1), (XMAX, XMAX), (XMAX, YMIN), (1, YMIN)]) + r"} \closedcycle;")
        L.append(r"\addplot[black!50,dashed,line width=0.5pt,forget plot] coordinates {" + fmt([(1, 1), (XMAX, XMAX)]) + "};")
        if api:
            pts = [(x * jitter(j), y) for j, (x, y) in enumerate(p["points"])]
            L.append(r"\addplot[polS,only marks,mark=*,mark size=0.6pt,opacity=0.3,forget plot] coordinates {" + fmt(pts) + "};")
            L.append(r"\addplot[black,only marks,mark=o,mark size=1.6pt,line width=0.6pt,forget plot] coordinates {" + fmt(p["run_medians"]) + "};")
        else:
            if p["points"]:
                L.append(r"\addplot[polS,only marks,mark=o,mark size=1.5pt,line width=0.7pt,mark options={fill=white},forget plot] coordinates {" + fmt(p["points"]) + "};")
            if p["crossed"]:
                L.append(r"\addplot[polS,only marks,mark=*,mark size=1.5pt,forget plot] coordinates {" + fmt(p["crossed"]) + "};")
    L += [r"\end{groupplot}",
          r"\node[font=\small,anchor=south] at ([xshift=0.11cm,yshift=0.62cm]group c1r1.north east) {API runs, cost in money};",
          r"\node[font=\small,anchor=south] at ([xshift=0.11cm,yshift=0.62cm]group c3r1.north east) {Self-hosted replays, cost in time};",
          r"\end{tikzpicture}",
          r"\caption{Repaying a summary. (a)~Time to decode one output token against context length on one GPU;",
          r"Qwen3.8-27B uses full attention in 16 of its 64 layers, Qwen3-32B in all 64; the open mark comes from a",
          r"later session. (b--e)~Estimated steps a summary must be used to repay its one-time cost, against the steps",
          r"it was used before the next summary; in the shaded area, the estimate is below the steps used. (b,c)~S",
          r"runs' summaries (dots, jittered), priced as in Table~\ref{tab:prices}; circles are run medians. (d,e)~S",
          r"replays of GLM switch points; the vertical position extrapolates the 20 replayed steps linearly, and filled",
          r"marks are replays whose reconstructed time fell below L's within them. Steps used come from the GLM run;",
          r"summaries cut short by the end of a run are left out here but stay in the costs of",
          r"Figures~\ref{fig:costparts} and~\ref{fig:cost}.}",
          r"\label{fig:payback}", r"\end{figure*}", END]
    tex = "\n".join(L) + "\n"
    (HERE / "payback-pgfplots.tex").write_text(tex)
    return tex


def paste(tex):
    main = PAPER / "main.tex"
    s = main.read_text()
    if BEGIN not in s or END not in s:
        raise SystemExit("markers not found in main.tex")
    a, b = s.index(BEGIN), s.index(END) + len(END) + 1
    main.write_text(s[:a] + tex + s[b:])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--paste", action="store_true")
    args = parser.parse_args()
    data = collect()
    (HERE / "payback-data.json").write_text(json.dumps(data, indent=1) + "\n")
    tex = write_tex(data)
    if args.paste:
        paste(tex)
    for p in data["panels"]:
        if "runs" in p:
            print(f"{p['title']:12s} summaries={len(p['points'])} runs={p['runs']} runs where most repaid={p['runs_mostly_repaid']}")
        else:
            print(f"{p['title']:12s} replays={p['n']} repaid within steps used={p['repaid']} crossed within 20={len(p['crossed'])}")

if __name__ == "__main__":
    main()
