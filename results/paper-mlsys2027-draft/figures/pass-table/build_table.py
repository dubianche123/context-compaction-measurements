"""Section 4 table: passed runs out of finished runs, by task, model, and policy; no provider or model calls.

Run from the repository root:
  python3 results/paper-mlsys2027-draft/figures/pass-table/build_table.py [--paste]
Inputs: prelim-numbers-20261003/runs.json (GLM runs and DeepSeek S/A, 2026-10-03 23:08 snapshot) and
deepseek-limitonly-numbers-20261004/deepseek-l-runs.json, the same runs as the cost figure. A run passed when the
official reward is 1. --paste replaces the generated block in main.tex so the manuscript stays self-contained.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parents[1]
ROOT = HERE.parents[3]
DIAG = ROOT / "results/harness-diagnosis-20260927"
BEGIN, END = "% BEGIN generated pass table", "% END generated pass table"
TASKS = [("mp-checkpoint-consolidation", "MP"), ("retro-console-soc", "Retro"), ("interleaved-vigenere", "Vig"),
         ("rs-archive-clone", "RS"), ("coq-block-bound", "Coq")]
COLUMNS = [("glm", "S"), ("glm", "A"), ("glm", "K"), ("glm", "L"), ("deepseek", "S"), ("deepseek", "A"), ("deepseek", "L")]


def collect():
    snap = json.loads((DIAG / "prelim-numbers-20261003/runs.json").read_text())
    dsl = json.loads((DIAG / "deepseek-limitonly-numbers-20261004/deepseek-l-runs.json").read_text())
    runs = [m for m in snap if m["model"] == "glm" or m["policy"] in ("S", "A")] + dsl
    cells = {}
    for task, short in TASKS:
        for model, policy in COLUMNS:
            sel = [m for m in runs if m["model"] == model and m["policy"] == policy and m["task"] == task]
            cells[f"{model}/{policy}/{short}"] = dict(passed=sum(m["reward"] == 1 for m in sel), runs=len(sel),
                                                      thresholds=sorted({m["thr"] for m in sel}))
    # how the failed runs ended: the eight-hour limit, an error that stopped the agent, or a finished run that
    # failed the tests. A run whose agent finished with a background command still running is reported with a
    # nonzero agent exit; it finished, so it is not counted as an error.
    endings = {}
    for model, policy in COLUMNS:
        failed = [m for m in runs if m["model"] == model and m["policy"] == policy and m["reward"] != 1]
        endings[f"{model}/{policy}"] = dict(
            time_limit=sum(m["exception"] == "AgentTimeoutError" for m in failed),
            error=sum(m["exception"] not in (None, "AgentTimeoutError") and not m.get("left_running") for m in failed),
            tests=sum(m["exception"] is None or bool(m.get("left_running")) for m in failed))
    left = [m for m in runs if m.get("left_running")]
    return dict(schema="pass-table/v3", cells=cells, failed_run_endings=endings,
                left_running=dict(runs=len(left), passed=sum(m["reward"] == 1 for m in left),
                                  passed_mp=sum(m["reward"] == 1 and m["task"] == "mp-checkpoint-consolidation" for m in left)),
                notes="passed = official reward 1; DeepSeek S/A exclude the Coq64 S run used only as a branch source")


def write_tex(data):
    L = [BEGIN, "% Generated by figures/pass-table/build_table.py; data in the same directory.",
         r"\begin{table}[t]", r"\centering\small",
         r"\caption{Passed runs out of finished runs. GLM's S and A pool the three thresholds, and K ran at 64K and",
         r"on Coq also at 32K; DeepSeek's S/A pairs ran at MP64, MP128, Retro32, Vig64, and RS64 (--:~none). L never",
         r"compacted. The last two rows count failed runs that hit the eight-hour limit or ended on an error; the",
         r"other failed runs finished and failed the tests."]
    lr = data["left_running"]
    if lr["runs"]:
        L.append(r"In \prelim{" + str(lr["runs"]) + r"} runs (\prelim{" + str(lr["passed"]) + r"} passed, \prelim{" +
                 str(lr["passed_mp"]) + r"} of them on MP), the agent finished while a background command it had started was still")
        L.append(r"running; the harness stopped the command before grading.")
    L[-1] += "}"
    L += [r"\label{tab:passes}",
          r"\begin{tabular}{@{}l*{4}{c}@{\hspace{1.4em}}*{3}{c}@{}}", r"\toprule",
          r"& \multicolumn{4}{c}{GLM} & \multicolumn{3}{c}{DeepSeek} \\",
          r"\cmidrule(r){2-5}\cmidrule(l){6-8}",
          r"Task & S & A & K & L & S & A & L \\", r"\midrule"]
    for _, short in TASKS:
        row = [short]
        for model, policy in COLUMNS:
            c = data["cells"][f"{model}/{policy}/{short}"]
            text = f"{c['passed']}/{c['runs']}" if c["runs"] else "--"
            row.append(r"\prelim{" + text + "}" if model == "glm" and c["runs"] else text)
        L.append(" & ".join(row) + r" \\")
    L.append(r"\midrule")
    for key, name in (("time_limit", "8-h limit"), ("error", "Error")):
        row = [name]
        for model, policy in COLUMNS:
            n = str(data["failed_run_endings"][f"{model}/{policy}"][key])
            row.append(r"\prelim{" + n + "}" if model == "glm" else n)
        L.append(" & ".join(row) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", END]
    tex = "\n".join(L) + "\n"
    (HERE / "pass-table.tex").write_text(tex)
    return tex


def paste(tex):
    main = PAPER / "main.tex"
    s = main.read_text()
    if BEGIN not in s or END not in s:
        raise SystemExit("markers not found in main.tex")
    a, b = s.index(BEGIN), s.index(END) + len(END) + 1
    main.write_text(s[:a] + tex + s[b:])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--paste", action="store_true")
    args = parser.parse_args()
    data = collect()
    (HERE / "pass-table-data.json").write_text(json.dumps(data, indent=1) + "\n")
    tex = write_tex(data)
    if args.paste:
        paste(tex)
    for model in ("glm", "deepseek"):
        for policy in "SAKL":
            c = [v for k, v in data["cells"].items() if k.startswith(f"{model}/{policy}/")]
            if sum(x["runs"] for x in c):
                e = data["failed_run_endings"][f"{model}/{policy}"]
                print(f"{model} {policy}: {sum(x['passed'] for x in c)}/{sum(x['runs'] for x in c)} passed; failed runs: "
                      f"{e['time_limit']} hit the time limit, {e['error']} ended on an error, {e['tests']} failed the tests")


if __name__ == "__main__":
    main()
